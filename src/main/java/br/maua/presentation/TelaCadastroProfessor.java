    private void entrarBotaoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_entrarBotaoActionPerformed
        // TODO add your handling code here:
        
        String nome = campoNome.getText();
        String senha = campoSenha.getText();
        String senhaConfirmacao = campoConfirmarSenha.getText();

        if (nome.isEmpty() || senhaConfirmacao.isEmpty() || senha.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Preencha todos os campos!");
            return;
        }

        JOptionPane.showMessageDialog(this,
            "Cadastro realizado com sucesso!");
        
        new TelaPainelDeControle().setVisible(true);
        this.dispose();

    }//GEN-LAST:event_entrarBotaoActionPerformed

